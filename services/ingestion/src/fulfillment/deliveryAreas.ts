/**
 * Published delivery-area settlement lists, one per storefront.
 *
 * Separated from `catalog.ts` purely for size: these are transcriptions of the
 * lists the retailers print on their own delivery pages, and inlining ~700 names
 * would bury the terms they belong to.
 *
 * WHY A LIST AND NOT `national`
 *
 * Every one of these storefronts was recorded as covering the whole country,
 * which is what an unfilled coverage row looks like. It is also the single most
 * expensive thing to get wrong here: `national` answers "yes, they deliver to
 * you" for every address in Israel, so a shopper in Eilat was being offered a
 * storefront that stops at Netanya. Rami Levy carried `national` at confidence
 * `verified`, and publishes a 270-settlement list.
 *
 * Names are stored exactly as the retailer writes them. Matching runs through
 * `canonicalizeCity`, whose alias table already collapses "תל אביב-יפו" and
 * "תל אביב" onto one key, so the retailer's spelling does not have to be
 * normalised here.
 *
 * WHAT IS DELIBERATELY MISSING
 *
 * Several lists also carry region phrases: "ישובי עמק חפר", "מושבי אופקים",
 * "קרית מלאכי והסביבה". They are dropped rather than stored, because a rule that
 * can never match is worse than an absent one: it reads as coverage in the table
 * and behaves as none. The cost is a false "not served" for a shopper in one of
 * those villages, which is the safe direction to be wrong about a delivery
 * promise. Each list notes how many phrases were dropped.
 */

